# ═══ 功能块：assign_ids —— 为条目按序补齐零填充 id（如 B001/A001） ═══
def assign_ids(items, prefix, width=3):
    """为条目按序补齐零填充 id（如 B001/A001）"""  # 原有 docstring
    for i, item in enumerate(items, 1):  # 从 1 开始编号遍历（1-based）
        item["id"] = f"{prefix}{i:0{width}d}"  # 前缀 + 按宽度零填充序号，如 B001/A020
    return items  # 原地修改后返回，便于链式调用


# ═══ 功能块：validate_benchmark —— 数据集质量校验：题数/id 唯一性/工具名/要点条数 ═══
def validate_benchmark(items):
    """校验数据集：题数、id 唯一性、expected_tools 合法性、ground_truth 条数。返回 (类别统计, 问题列表)"""  # 原有 docstring
    problems = []  # 问题清单累积器（空列表=校验通过）
    cats = Counter(i["category"] for i in items)  # 按类别统计题数
    ids = [i["id"] for i in items]  # 收集全部 id
    if len(items) != 120:  # 总题数硬校验（七大类合计 120）
        problems.append(f"总题数应为120，实际{len(items)}")  # 记录题数不符
    if len(set(ids)) != len(ids):  # 去重后数量不等说明 id 有重复
        problems.append("存在重复 id")  # 记录重复 id
    for i in items:  # 逐题细粒度校验
        for t in i["expected_tools"]:  # 遍历该题预期工具链
            if t not in VALID_TOOLS:  # 工具名不在白名单
                problems.append(f"{i['id']} 非法工具名 {t}")  # 记录非法工具名
        if not (3 <= len(i["ground_truth"]) <= 6):  # 评分要点条数须在 3-6 之间
            problems.append(f"{i['id']} ground_truth 条数为 {len(i['ground_truth'])}（应3-6）")  # 记录条数越界
    return cats, problems  # 返回 (类别统计, 问题清单)


