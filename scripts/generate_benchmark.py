# ═══ 功能块：_prod —— 型号查询题的模板工厂：型号 + 焦点参数 → 一条完整评测题 ═══
def _prod(question, model, focus, note, difficulty="easy"):
    """生成一条型号查询题：ground_truth 含焦点参数 + 品牌/代码 + 相邻参数。"""
    p = PRODUCTS[model]  # 取该型号的规格事实 dict
    order = ["cuff", "power", "memory", "features"]  # 参数键序：用于选取"相邻参数"
    other = order[(order.index(focus) + 1) % len(order)]  # 焦点参数的下一个参数（环形取模，丰富答案覆盖面）
    return {  # 组装一条评测题
        "category": "型号查询",  # 类别固定：型号查询
        "question": question,  # 用户问题文本
        "expected_tools": ["product_lookup"],  # 预期工具：型号查询（单一工具）
        "ground_truth": [  # 答案要点列表（评测打分依据）
            p[focus],  # 要点1：焦点参数事实（本题核心考点）
            f"产品代码为{p['code']}，品牌为{p['brand']}",  # 要点2：代码与品牌
            "类型为上臂式电子血压计",  # 要点3：固定类型描述
            p[other],  # 要点4：相邻参数事实（顺带考察能力）
        ],
        "difficulty": difficulty,  # 难度标签
        "note": note,  # 出题说明
    }


